const LANGUAGE_STORAGE_KEY = 'securechat_app_language';

export function loadAppLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY) as AppLanguage | null;
    if (saved && (saved === 'en' || saved === 'rw' || saved === 'es' || saved === 'fr')) {
      return saved;
    }
  } catch (e) {
    console.error('Failed to load language', e);
  }
  return 'en';
}

export function saveAppLanguage(lang: AppLanguage): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch (e) {
    console.error('Failed to save language', e);
  }
}

export function t(key: string, lang: AppLanguage = 'en'): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dictionary[key] || TRANSLATIONS.en[key] || key;
}
